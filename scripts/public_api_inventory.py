#!/usr/bin/env python3
"""Generate a deterministic source-level inventory of the public Cangjie API."""

from __future__ import annotations

import argparse
import difflib
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parent.parent
SNAPSHOT = ROOT / "api" / "public-api.txt"
START = re.compile(r"^(?:public\s+|protected\s+|extend\s+|sealed\s+)")


def source_files() -> list[Path]:
    roots = [ROOT / "src", *(ROOT / "packages").glob("*/src")]
    files: list[Path] = []
    for source_root in roots:
        if not source_root.is_dir():
            continue
        for path in source_root.rglob("*.cj"):
            if path.name.endswith("_test.cj"):
                continue
            files.append(path)
    return sorted(files, key=lambda path: path.relative_to(ROOT).as_posix())


def strip_line_comment(line: str) -> str:
    """Remove // outside ordinary strings; declarations do not use multiline strings."""
    escaped = False
    quote = ""
    index = 0
    while index < len(line):
        char = line[index]
        if quote:
            if escaped:
                escaped = False
            elif char == "\\" and quote == '"':
                escaped = True
            elif char == quote:
                quote = ""
            index += 1
            continue
        if char in {'"', "'"}:
            quote = char
            index += 1
            continue
        if char == "/" and index + 1 < len(line) and line[index + 1] == "/":
            return line[:index]
        index += 1
    return line


def normalize(text: str) -> str:
    return re.sub(r"\s+", " ", text).strip()


def brace_delta(text: str) -> int:
    """Count braces outside ordinary strings and line comments."""
    code = strip_line_comment(text)
    escaped = False
    quote = ""
    delta = 0
    for char in code:
        if quote:
            if escaped:
                escaped = False
            elif char == "\\" and quote == '"':
                escaped = True
            elif char == quote:
                quote = ""
            continue
        if char in {'"', "'"}:
            quote = char
        elif char == "{":
            delta += 1
        elif char == "}":
            delta -= 1
    return delta


def has_open_brace(text: str) -> bool:
    code = strip_line_comment(text)
    escaped = False
    quote = ""
    for char in code:
        if quote:
            if escaped:
                escaped = False
            elif char == "\\" and quote == '"':
                escaped = True
            elif char == quote:
                quote = ""
            continue
        if char in {'"', "'"}:
            quote = char
        elif char == "{":
            return True
    return False


def declaration_header(lines: list[str], start: int) -> tuple[str, int]:
    parts: list[str] = []
    parens = 0
    index = start
    while index < len(lines):
        clean = strip_line_comment(lines[index]).strip()
        if clean:
            before_body = clean.split("{", 1)[0].strip()
            if before_body:
                parts.append(before_body)
            parens += clean.count("(") - clean.count(")")
        if "{" in clean or (index > start and parens <= 0) or (
            index == start and parens <= 0 and not clean.endswith(",")
        ):
            break
        index += 1
    return normalize(" ".join(parts)), index


def full_public_type(lines: list[str], start: int) -> tuple[str, int]:
    parts: list[str] = []
    depth = 0
    opened = False
    index = start
    while index < len(lines):
        clean = strip_line_comment(lines[index]).strip()
        if clean:
            parts.append(clean)
        change = brace_delta(lines[index])
        if has_open_brace(lines[index]):
            opened = True
        depth += change
        if opened and depth <= 0:
            break
        index += 1
    return normalize(" ".join(parts)), index


def declarations(path: Path) -> list[str]:
    lines = path.read_text(encoding="utf-8").splitlines()
    result: list[str] = []
    index = 0
    while index < len(lines):
        clean = strip_line_comment(lines[index]).strip()
        if not START.match(clean):
            index += 1
            continue
        if re.match(r"^(?:public\s+)?(?:sealed\s+)?(?:enum|interface)\s+", clean):
            item, index = full_public_type(lines, index)
        else:
            item, index = declaration_header(lines, index)
        if item:
            result.append(item)
        index += 1
    return result


def render() -> str:
    output = [
        "# Cangjie TOML public API inventory",
        "# Generated by scripts/public_api_inventory.py; do not edit manually.",
        "# Scope: explicit public/protected/extend and implicitly public sealed declarations,",
        "# plus complete public enum/interface blocks.",
        "# This is a source-level drift guard, not ABI or semantic compatibility proof.",
        "",
    ]
    for path in source_files():
        items = declarations(path)
        if not items:
            continue
        output.append(f"[{path.relative_to(ROOT).as_posix()}]")
        output.extend(items)
        output.append("")
    return "\n".join(output).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser()
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="replace the snapshot")
    mode.add_argument("--check", action="store_true", help="verify the snapshot")
    args = parser.parse_args()

    actual = render()
    if args.write:
        SNAPSHOT.parent.mkdir(parents=True, exist_ok=True)
        SNAPSHOT.write_text(actual, encoding="utf-8")
        print(f"wrote {SNAPSHOT.relative_to(ROOT)}")
        return 0
    if not SNAPSHOT.exists():
        print(f"missing {SNAPSHOT.relative_to(ROOT)}; run with --write", file=sys.stderr)
        return 1
    expected = SNAPSHOT.read_text(encoding="utf-8")
    if expected == actual:
        print("public API inventory is current")
        return 0
    sys.stderr.writelines(
        difflib.unified_diff(
            expected.splitlines(keepends=True),
            actual.splitlines(keepends=True),
            fromfile=str(SNAPSHOT.relative_to(ROOT)),
            tofile="generated",
        )
    )
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
